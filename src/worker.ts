/** Public mount path for the v2 app. Must match SvelteKit kit.paths.base.
 * NOTE: must NOT be exported — workerd requires every top-level export of the
 * entry module to be a handler/DO class, and a string export crashes startup. */
const BASE_PATH = "/v2";

const mcpHandlerV2 = TranslationHelpsMCP.serve(`${BASE_PATH}/mcp`, {
  binding: "MCP_AGENT",
});
const mcpHandlerRoot = TranslationHelpsMCP.serve("/mcp", {
  binding: "MCP_AGENT",
});

export { TranslationHelpsMCP };

export interface Env extends DispatchEnv {
  MCP_AGENT: DurableObjectNamespace;
  TRANSLATION_HELPS_CACHE: KVNamespace;
  ZIP_FILES: R2Bucket;
  LANGUAGE_PACKS: R2Bucket;
  ANALYTICS: AnalyticsEngineDataset;
  API?: Fetcher;
  API_BASE_URL?: string;
  TOOL_SECRET?: string;
  /** Optional Bearer/X-Api-Key for /mcp. Unset = anonymous public access. */
  MCP_API_KEY?: string;
  /** Max requests/min per IP for /mcp and /api/tool. Default 90; 0 = off. */
  RATE_LIMIT_RPM?: string;
  /** Max part requests/min per IP for /v2/packs/parts/, counted apart. Default 600; 0 = off. */
  PARTS_RATE_LIMIT_RPM?: string;
  /** `on` lets this Worker ask for parts builds (preview and production); unset, or anything else, is off. */
  PACKS_PARTS_DISPATCH?: string;
  /** Counted parts dispatches a day, apart from f1.1's cap of 20. Default 20; 0 = none. */
  PACKS_PARTS_DAILY_CAP?: string;
  /** `parts`: the cron never runs the f1.1 sweep (staging). Unset sweeps f1.1 at 06 UTC as before. */
  PACKS_SWEEP?: string;
  /** `dry-run` or `delete` runs the parts cleanup at 03 UTC (retried at 04 and 05); unset (or anything else) is off. */
  PACKS_CLEANUP?: string;
  /** Parts checks in one run of the hourly parts slice. Default 5 (the Free plan's 50 outside fetches); 0 = none. */
  PARTS_CHECKS_PER_RUN?: string;
  OPENAI_API_KEY?: string;
  ASSETS: Fetcher;
  BASE_PATH?: string;
}

const MCP_CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "GET, POST, DELETE, OPTIONS",
  "Access-Control-Allow-Headers":
    "Content-Type, Authorization, X-Api-Key, Mcp-Session-Id",
};

function mcpSessionId(request: Request): string | null {
  const value = request.headers.get("mcp-session-id");
  if (value === null) return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

/** GET/DELETE (and anything else) with no session: no stream, no Durable Object. */
function mcpMethodNotAllowed(): Response {
  return new Response(
    JSON.stringify({
      jsonrpc: "2.0",
      id: null,
      error: { code: -32000, message: "Method not allowed." },
    }),
    {
      status: 405,
      headers: {
        Allow: "POST",
        "Content-Type": "application/json",
        ...MCP_CORS,
      },
    },
  );
}

function withMcpCors(response: Response): Response {
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(MCP_CORS)) {
    headers.set(name, value);
  }
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

export default {
  async fetch(
    request: Request,
    env: Env,
    ctx: ExecutionContext,
  ): Promise<Response> {
    const url = new URL(request.url);
    const base = (env.BASE_PATH || BASE_PATH).replace(/\/$/, "") || "/v2";

    if (url.pathname === "/" || url.pathname === "") {
      return Response.redirect(new URL(`${base}/`, url).toString(), 302);
    }

    const isMcpRoot =
      url.pathname === "/mcp" || url.pathname.startsWith("/mcp/");
    const isMcpV2 =
      url.pathname === `${base}/mcp` || url.pathname.startsWith(`${base}/mcp/`);

    if (isMcpRoot || isMcpV2) {
      if (request.method === "OPTIONS") {
        return new Response(null, { status: 204, headers: MCP_CORS });
      }
      const authDenied = enforceOptionalMcpApiKey(
        request,
        env.MCP_API_KEY,
        MCP_CORS,
      );
      if (authDenied) return authDenied;
      const limited = enforceRateLimit(request, env.RATE_LIMIT_RPM, MCP_CORS);
      if (limited) return limited;

      // A session opened before this deploy, or a client that still speaks
      // the sessionful transport, keeps using the Durable Object.
      if (mcpSessionId(request)) {
        if (isMcpRoot) return mcpHandlerRoot.fetch(request, env, ctx);
        return mcpHandlerV2.fetch(request, env, ctx);
      }

      // Stateless servers do not offer a standalone SSE stream or a session
      // to delete. Answer 405 here so the transport never opens one.
      if (request.method !== "POST") {
        return mcpMethodNotAllowed();
      }

      const statelessEnv: ToolEnv = {
        ...env,
        waitUntil: (promise: Promise<unknown>) => {
          ctx.waitUntil(promise);
        },
      };
      return withMcpCors(
        await handleStatelessMcpRequest(request, statelessEnv),
      );
    }

    if (
      (url.pathname === `${base}/api/tool` || url.pathname === "/api/tool") &&
      (request.method === "POST" || request.method === "OPTIONS")
    ) {
      return handleToolCall(request, env);
    }

    if (
      (url.pathname === `${base}/api/mcp-manifest` ||
        url.pathname === "/api/mcp-manifest") &&
      request.method === "GET"
    ) {
      return new Response(
        JSON.stringify(buildMcpManifest({ mcpEndpoint: `${base}/mcp` })),
        {
          status: 200,
          headers: {
            "Content-Type": "application/json",
            "Access-Control-Allow-Origin": "*",
          },
        },
      );
    }

    const packsPrefix = `${base}/packs/`;
    if (url.pathname.startsWith(packsPrefix)) {
      return handlePacks(
        request,
        env,
        ctx,
        url.pathname.slice(packsPrefix.length),
      );
    }

    // SvelteKit SSR + static assets under /v2
    return svelteKit.fetch(request, env, ctx);
  },

  /**
   * The packs crons (see wrangler.toml and src/packs/scheduled.ts): the cron string picks the job, the schedule's
   * time its hour and day. Awaited, as Cloudflare documents for one task: the runtime waits for the handler's promise
   * (up to a cron's 15 min), and the job, not a waitUntil after it, is the invocation.
   */
  async scheduled(
    event: ScheduledController,
    env: Env,
    ctx: ExecutionContext,
  ): Promise<void> {
    await runScheduled(env, ctx, {
      cron: event.cron,
      scheduledTime: event.scheduledTime,
    });
  },
};

async function handleToolCall(request: Request, env: Env): Promise<Response> {
  const cors = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type, X-Tool-Secret",
  };

  if (request.method === "OPTIONS") {
    return new Response(null, { status: 204, headers: cors });
  }

  const limited = enforceRateLimit(request, env.RATE_LIMIT_RPM, cors);
  if (limited) return limited;

  if (env.TOOL_SECRET) {
    const provided = request.headers.get("X-Tool-Secret");
    if (provided !== env.TOOL_SECRET) {
      return new Response(JSON.stringify({ error: "Unauthorized" }), {
        status: 401,
        headers: { "Content-Type": "application/json", ...cors },
      });
    }
  }

  let body: {
    name?: string;
    params?: Record<string, unknown>;
    requestId?: string;
  };
  try {
    body = await request.json();
  } catch {
    return new Response(JSON.stringify({ error: "Invalid JSON body" }), {
      status: 400,
      headers: { "Content-Type": "application/json", ...cors },
    });
  }

  const { name, params = {}, requestId = crypto.randomUUID() } = body;
  if (!name) {
    return new Response(JSON.stringify({ error: "Missing tool name" }), {
      status: 400,
      headers: { "Content-Type": "application/json", ...cors },
    });
  }

  const tool = TOOL_REGISTRY[name];
  if (!tool) {
    return new Response(JSON.stringify({ error: `Unknown tool: "${name}"` }), {
      status: 404,
      headers: { "Content-Type": "application/json", ...cors },
    });
  }

  try {
    const normalized = normalizeToolArgs(name, params);
    const validated = tool.inputSchema.parse(normalized);
    const result = await tool.handler(validated, env, requestId);

    return new Response(
      JSON.stringify({
        structuredContent: result.structuredContent,
        content: result.content,
      }),
      { status: 200, headers: { "Content-Type": "application/json", ...cors } },
    );
  } catch (err) {
    if (isTranslationHelpsError(err)) {
      return new Response(
        JSON.stringify({
          error: err.message,
          code: err.code,
          content: [
            {
              type: "text",
              text: `Error ${err.code}: ${err.message}`,
            },
          ],
          isError: true,
        }),
        {
          status: err.statusCode,
          headers: { "Content-Type": "application/json", ...cors },
        },
      );
    }
    if (err instanceof ApiClientError && err.status === 404) {
      const notAvail = {
        available: false,
        code: "RESOURCE_NOT_AVAILABLE",
        message: err.message,
      };
      return new Response(
        JSON.stringify({
          structuredContent: notAvail,
          content: [{ type: "text", text: JSON.stringify(notAvail) }],
        }),
        {
          status: 200,
          headers: { "Content-Type": "application/json", ...cors },
        },
      );
    }
    const message = err instanceof Error ? err.message : String(err);
    logger.error("tool:error", { name, message });
    return new Response(JSON.stringify({ error: message }), {
      status: 400,
      headers: { "Content-Type": "application/json", ...cors },
    });
  }
}
